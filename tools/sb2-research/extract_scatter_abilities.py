"""Extrai ramos simples de atributos sem confundir ROM com validacao dinamica."""
import hashlib
import json
import struct
import sys
from pathlib import Path


def extract(rom_path):
    rom = Path(rom_path).read_bytes()
    digest = hashlib.sha256(rom).hexdigest()
    if digest != 'dcf9cd8615a08c8050fd102702291808cafaffd428013f2dda3164130b7f08fd':
        raise ValueError('ROM diverge da identidade conferida')
    branches = []
    for handler, name, address, offset, glyph in (
        (4, 'Glove', 0xc0903e, 0xfe, 0x1626),
        (5, 'Kick', 0xc09058, 0xff, 0x1624),
        (10, 'unmapped-1608', 0xc09116, 0xfa, 0x1608),
        (11, 'unmapped-1620', 0xc09130, 0xfb, 0x1620),
    ):
        # LDY atributo; SEP20; LDA[82],Y; BEQ fim; DEC; STA[82],Y;
        # REP20; LDA glifo; STA7E5C84; REP20; JMP8F37.
        expected = (bytes([0xa0, offset, 0, 0xe2, 0x20, 0xb7, 0x82, 0xf0,
                           0x0c, 0x3a, 0x97, 0x82, 0xc2, 0x20, 0xa9])
                    + struct.pack('<H', glyph)
                    + bytes.fromhex('8f845c7ec2204c378f'))
        raw = rom[address - 0xc00000:address - 0xc00000 + len(expected)]
        if raw != expected:
            raise ValueError(f'Ramo inesperado em {address:06X}')
        branches.append({'handler': handler, 'name': name, 'address': hex(address),
                         'player_offset': offset, 'glyph': glyph, 'raw_hex': raw.hex(),
                         'operation': 'if byte>0: decrement byte; emit glyph'})
    offsets = list(rom[0x5ff7d:0x5ff7d + 14])
    glyphs = list(struct.unpack_from('<14H', rom, 0x5f205))
    result = {'authority': 'shipped ROM bytes; exact simple-branch decoding',
              'rom_sha256': digest, 'simple_scatter_branches': branches,
              'return_selector_glove': {'selector': 7, 'player_offset': offsets[7],
                                        'glyph': glyphs[7]},
              'limitations': ['Glove scatter and return not dynamically validated.',
                              'No runtime implementation generated by this extractor.',
                              'Unmapped glyph names intentionally remain unknown.']}
    if offsets[7] != 0xfe or glyphs[7] != 0x1626:
        raise ValueError('Seletor de retorno da luva diverge')
    Path('docs/sb2/SB2-STAGE12-SCATTER-ABILITY-BRANCHES-ROM.json').write_text(
        json.dumps(result, indent=2) + '\n', encoding='utf-8')
    print({'simple_branches': len(branches), 'glove_return_selector': 7})


if __name__ == '__main__':
    extract(sys.argv[1])
